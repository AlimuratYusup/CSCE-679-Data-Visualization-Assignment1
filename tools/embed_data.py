"""
embed_data.py
-----------------------------------------------------------------------------
Copy temperature_daily.csv into js/temperature-data.js so the pages also work
when the HTML file is opened directly from disk (file://), where browsers
block reading the CSV with fetch.

Run it again whenever temperature_daily.csv changes:
    python tools/embed_data.py
"""

from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = PROJECT_ROOT / "temperature_daily.csv"
OUTPUT_PATH = PROJECT_ROOT / "js" / "temperature-data.js"
NAMESPACE = "TemperatureHeatmap"
VARIABLE_NAME = "EMBEDDED_TEMPERATURE_CSV"


def build_script(csv_text: str) -> str:
    """Wrap the raw CSV text in a JS file that stores it on the shared namespace."""
    escaped_csv = csv_text.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
    return (
        "/**\n"
        " * temperature-data.js  (GENERATED by tools/embed_data.py; do not edit by hand)\n"
        " * Copy of temperature_daily.csv used when the page is opened from disk (file://).\n"
        " */\n\n"
        f"window.{NAMESPACE} = window.{NAMESPACE} || {{}};\n"
        f"window.{NAMESPACE}.{VARIABLE_NAME} = `{escaped_csv}`;\n"
    )


def main() -> None:
    csv_text = CSV_PATH.read_text(encoding="utf-8").replace("\r\n", "\n")
    OUTPUT_PATH.write_text(build_script(csv_text), encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH.relative_to(PROJECT_ROOT)} ({csv_text.count(chr(10))} lines of CSV)")


if __name__ == "__main__":
    main()
